import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const read = (relative) => JSON.parse(fs.readFileSync(path.join(ROOT, relative), 'utf8'));
const write = (relative, text) => fs.writeFileSync(path.join(ROOT, relative), text);

/** Recursively overlay plain objects (arrays and scalars replace) — used for local audio overrides. */
function merge(target, patch) {
  if (!patch || typeof patch !== 'object' || Array.isArray(patch)) return patch;
  const out = target && typeof target === 'object' && !Array.isArray(target) ? target : {};
  for (const [k, v] of Object.entries(patch)) out[k] = v && typeof v === 'object' && !Array.isArray(v) ? merge(out[k], v) : v;
  return out;
}

/** Apply project-owned art and audio without rebuilding combat data or browser catalogues. */
export function applyContentAssets(assets, { operators, enemies } = {}) {
  const definitions = (kind) => read(`content/${kind}/index.json`).map((entry) => {
    if (!/^[a-z0-9_-]+\.json$/.test(entry.file)) throw Error('Invalid content definition filename');
    const d = read(`content/${kind}/${entry.file}`);
    if (kind === 'enemies' && d.key !== entry.key) throw Error(`Enemy key mismatch in ${entry.file}`);
    return d;
  });
  operators ??= definitions('operators');
  enemies ??= definitions('enemies');
  assets.chars ||= {};
  for (const d of operators) {
    assets.chars[d.charId] = d.art;
    Object.assign(assets.skills ||= {}, d.skillAssets);
    Object.assign(assets.skillsById ||= {}, d.skillAliases);
    Object.assign(assets.modules ||= {}, d.moduleAssets);
    for (const [tree, bank] of Object.entries(d.voiceAssets || {})) {
      assets.audio ||= {};
      assets.audio[tree] ||= {};
      assets.audio[tree][d.record.assets?.voice || d.charId] = bank;
    }
    if (d.audio) {
      assets.audio ||= {};
      assets.audio.sfx ||= {};
      assets.audio.sfx.units ||= {};
      assets.audio.sfx.units[d.charId] = merge(assets.audio.sfx.units[d.charId], d.audio);
    }
  }
  assets.enemies ||= {};
  for (const d of enemies) assets.enemies[d.key] = d.art;
  return assets;
}

/** Compile local operator definitions into the existing browser/simulation data format. */
export function buildContent({ operator = null } = {}) {
  const catalog = read('content/operators/index.json');
  const entries = operator ? catalog.filter((entry) => entry.id === operator) : catalog;
  if (!entries.length) throw Error('Unknown operator');
  const definitions = entries.map((entry) => {
    if (!/^[a-z0-9-]+\.json$/.test(entry.file)) throw Error('Invalid operator definition filename');
    return read(`content/operators/${entry.file}`);
  });
  const chess = read('data/chess.json'), units = chess.units || chess;
  const assets = read('data/assets.json'), backups = read('data/backups.json');
  for (const d of definitions) {
    units[d.chessId] = d.record;
    if (d.selection) {
      backups.units[d.charId] = d.selection.unit;
      if (d.selection.operator) backups.diy.operators[d.charId] = d.selection.operator;
      if (d.selection.owned && !backups.diy.ownedPool.includes(d.charId)) backups.diy.ownedPool.push(d.charId);
    }
  }
  const roster = catalog.map((entry) => {
    const d = read(`content/operators/${entry.file}`);
    return { slot: entry.slot, id: d.chessId, name: entry.name, owner: entry.owner, ready: true };
  });
  const tierKits = catalog.filter((entry) => entry.tier).map(({ tier, kit }) => ({ tier, file: kit }));
  const operatorKits = catalog.filter((entry) => !entry.tier).map((entry) => entry.kit);

  // 自设敌人：content/enemies/index.json 登记的条目写进官方数据的两张表。
  // 炙烤 / 焦香螺旋桨原先靠手工注入 data/，重跑 fetch-assets 会被上游重建冲掉，因此改成走生成流程。
  const enemyIndex = read('content/enemies/index.json');
  const enemyDefs = enemyIndex.map((entry) => {
    if (!/^[a-z0-9_-]+\.json$/.test(entry.file)) throw Error('Invalid enemy definition filename');
    const d = read(`content/enemies/${entry.file}`);
    if (d.key !== entry.key) throw Error(`Enemy key mismatch in ${entry.file}`);
    return d;
  });
  if (enemyDefs.length) {
    const enemies = read('data/enemies.json');
    for (const d of enemyDefs) {
      enemies[d.key] = d.record;
    }
    write('data/enemies.json', JSON.stringify(enemies));
  }

  applyContentAssets(assets, { operators: definitions, enemies: enemyDefs });

  // All output paths are fixed under this project; importing an AKF never writes another project.
  write('data/chess.json', JSON.stringify(chess));
  write('data/assets.json', JSON.stringify(assets));
  write('data/backups.json', JSON.stringify(backups));
  write('public/sandbox/js/generated-ops.js', `// Generated by tools/build-content.mjs from content/operators/index.json.\nexport const CUSTOM_OPS = Object.freeze(${JSON.stringify(roster, null, 2)});\n`);
  write('server/sim/content/kits/custom-catalog.js', `// Generated by tools/build-content.mjs.\nexport const CUSTOM_TIER_KITS = Object.freeze(${JSON.stringify(tierKits)});\nexport const CUSTOM_OPERATOR_KITS = Object.freeze(${JSON.stringify(operatorKits)});\n`);
  return entries.map((entry) => entry.id);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.length && (args.length !== 2 || args[0] !== '--operator')) throw Error('Usage: node tools/build-content.mjs [--operator id]');
  console.log(`Updated SI content: ${buildContent({ operator: args[1] || null }).join(', ')}`);
}
