"""Import complete operator artwork from AKDP image releases for the SI roster."""
import argparse
import hashlib
import json
from io import BytesIO
from pathlib import Path
from zipfile import ZipFile

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]


def read(path):
    return json.loads((ROOT / path).read_text(encoding="utf-8-sig"))


def framing(payload):
    with Image.open(BytesIO(payload)) as image:
        width, height = image.size
        alpha = image.convert("RGBA").getchannel("A")
        bounds = alpha.point(lambda value: 255 if value >= 12 else 0).getbbox()
        left, top, right, bottom = bounds or (0, 0, width, height)
        return {"width": width, "height": height,
                "bounds": [left, top, right - left, bottom - top]}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--index", default=".cache/operator-illustrations/index.json")
    parser.add_argument("--archives", default=".cache/operator-illustrations")
    args = parser.parse_args()
    index = read(args.index)
    operators = read("data/operator-library.json")["operators"]
    archives = [ZipFile(path) for path in sorted((ROOT / args.archives).glob("*.zip"))]
    try:
        files = {}
        for archive in archives:
            for entry in archive.infolist():
                files.setdefault(Path(entry.filename).name, []).append((archive, entry))
        jobs = []
        for operator in operators.values():
            char_id = operator["charId"]
            phase = 2 if char_id + "#2" in index["artworks"] else 1
            key = f"{char_id}#{phase}"
            artwork = index["artworks"].get(key)
            if not artwork:
                raise ValueError(f"No complete artwork for {operator['name']} ({char_id})")
            source = artwork["large"]
            candidates = files.get(source["file"], [])
            payload = next((data for archive, entry in candidates
                            if hashlib.sha256(data := archive.read(entry)).hexdigest() == source["sha256"]), None)
            if payload is None:
                raise ValueError(f"Missing image release for {key}: {source['file']} since {artwork.get('sinceVersion')}")
            jobs.append((char_id, phase, key, source, payload))
        registry, provenance = {}, {}
        destination = ROOT / "public/assets/char/illust"
        destination.mkdir(parents=True, exist_ok=True)
        for char_id, phase, key, source, payload in jobs:
            filename = f"{char_id}_{phase}.png"
            (destination / filename).write_bytes(payload)
            registry[char_id] = {"url": f"/assets/char/illust/{filename}", "phase": phase, **framing(payload)}
            provenance[char_id] = {"artwork": key, "file": source["file"], "sha256": source["sha256"]}
        for entry in read("content/operators/index.json"):
            definition = read("content/operators/" + entry["file"])
            art = definition["art"]
            url = art.get("illust") or art.get("portraitE2") or art["portrait"]
            payload = (ROOT / "public" / url.lstrip("/")).read_bytes()
            registry[definition["charId"]] = {"url": url, "phase": 2, **framing(payload)}
            provenance[definition["charId"]] = {"file": url, "sha256": hashlib.sha256(payload).hexdigest()}
        target = ROOT / "public/sandbox/js/generated-illustrations.js"
        target.write_text("// Generated by tools/import-operator-illustrations.py.\n"
                          "export const OPERATOR_ILLUSTRATIONS = Object.freeze("
                          + json.dumps(registry, ensure_ascii=False, indent=2) + ");\n", encoding="utf-8")
        ledger = {"source": "3aKHP/arknights-data-pipeline", "version": index["currentVersion"],
                  "index": "https://github.com/3aKHP/arknights-data-pipeline/releases/tag/images-" + index["currentVersion"],
                  "operators": provenance}
        (ROOT / "art/operator-illustrations.json").write_text(
            json.dumps(ledger, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"Imported complete illustrations for {len(registry)} operators")
    finally:
        for archive in archives:
            archive.close()


if __name__ == "__main__":
    main()
